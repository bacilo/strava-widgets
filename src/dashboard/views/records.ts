function buildRiegelTable(matrix: RiegelMatrix): HTMLElement {
  const table = document.createElement('table');
  table.className = 'activity-table pr-table';

  const thead = document.createElement('thead');
  const headRow = document.createElement('tr');
  const corner = document.createElement('th');
  corner.textContent = 'From \\ To';
  headRow.appendChild(corner);
  for (const column of matrix.columns) {
    const th = document.createElement('th');
    th.className = 'pr-table__numeric';
    th.textContent = DISTANCE_LABELS[column];
    headRow.appendChild(th);
  }
  thead.appendChild(headRow);
  table.appendChild(thead);

  const tbody = document.createElement('tbody');
  matrix.rows.forEach((fromDistance, rowIndex) => {
    const tr = document.createElement('tr');

    const rowHeader = document.createElement('th');
    rowHeader.textContent = DISTANCE_LABELS[fromDistance];
    tr.appendChild(rowHeader);

    for (const cell of matrix.cells[rowIndex]) {
      const td = document.createElement('td');
      td.className = 'pr-table__numeric';
      td.textContent = `${formatEffortDuration(cell.predictedSec)} `;
      if (cell.isActual) {
        const em = document.createElement('em');
        em.textContent = '(actual)';
        td.appendChild(em);
      }
      tr.appendChild(td);
    }

    tbody.appendChild(tr);
  });
  table.appendChild(tbody);

  return table;
}

function buildPredictionsSection(bestEfforts: BestEffortsDocument): { section: HTMLElement; heading: HTMLElement } {
  const section = document.createElement('section');
  section.id = 'records-predictions';

  const heading = document.createElement('h2');
  heading.className = 'text-heading';
  heading.tabIndex = -1;
  heading.textContent = 'Race Predictions';
  section.appendChild(heading);

  const card = document.createElement('div');
  card.className = 'card detail-section';

  const rankings = bestEfforts.rankings;

  const standardLabel = document.createElement('p');
  standardLabel.className = 'text-label';
  standardLabel.textContent = 'Standard (b = 1.06)';
  card.appendChild(standardLabel);

  if (isEmptyRanking(rankings.marathon)) {
    const marathonNote = document.createElement('p');
    marathonNote.className = 'text-body';
    marathonNote.textContent =
      'No marathon has been run yet — this row is a Riegel-based estimate, not a recorded time.';
    card.appendChild(marathonNote);
  }

  card.appendChild(buildRiegelTable(buildRiegelMatrix(rankings)));

  const fitPoints = selectFitPoints(rankings);
  const fit = fitRiegelExponent(fitPoints);

  if (fit) {
    const fittedLabel = document.createElement('p');
    fittedLabel.className = 'text-label';
    const distanceNames = fit.distances.map((d) => DISTANCE_LABELS[d]).join(', ');
    fittedLabel.textContent = `Fitted exponent: b = ${fit.b.toFixed(3)} (from ${distanceNames}) — using rank-1 PRs only.`;
    card.appendChild(fittedLabel);

    card.appendChild(buildRiegelTable(buildRiegelMatrix(rankings, fit.b)));
  } else {
    const distinctCount = new Set(fitPoints.map((p) => p.activityId)).size;
    const suppression = document.createElement('p');
    suppression.className = 'text-body';
    suppression.textContent = `A fitted personal exponent isn't shown yet — it needs PRs from at least 3 different runs (currently ${distinctCount}).`;
    card.appendChild(suppression);
  }

  section.appendChild(card);
  return { section, heading };
}

