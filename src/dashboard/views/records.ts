function buildProgressionTable(series: readonly EvolutionPoint[]): HTMLElement {
  const table = document.createElement('table');
  table.className = 'activity-table pr-table';

  const thead = document.createElement('thead');
  const headRow = document.createElement('tr');
  for (const label of ['Date', 'Time', 'Improvement', 'Run']) {
    const th = document.createElement('th');
    th.textContent = label;
    headRow.appendChild(th);
  }
  thead.appendChild(headRow);
  table.appendChild(thead);

  const tbody = document.createElement('tbody');
  for (const row of buildProgressionRows(series)) {
    const tr = document.createElement('tr');

    const dateTd = document.createElement('td');
    dateTd.textContent = formatActivityDate(row.startDate);
    tr.appendChild(dateTd);

    const timeTd = document.createElement('td');
    timeTd.textContent = formatEffortDuration(row.durationSec);
    tr.appendChild(timeTd);

    const improvementTd = document.createElement('td');
    improvementTd.textContent =
      row.improvementSec === null ? '—' : `−${formatEffortDuration(Math.abs(row.improvementSec))}`;
    tr.appendChild(improvementTd);

    const runTd = document.createElement('td');
    const cta = document.createElement('a');
    cta.className = 'cta';
    cta.textContent = 'View Activity';
    cta.href = `#/activity/${row.activityId}`;
    runTd.appendChild(cta);
    tr.appendChild(runTd);

    tbody.appendChild(tr);
  }
  table.appendChild(tbody);

  return table;
}

/**
 * Builds one evolution card. A distance with an empty series (marathon
 * today) renders its heading, an em-dash value, and a named "no PR history"
 * label — never a blank card, and no `<canvas>`/`<details>` at all, so the
 * caller never hands an empty series to `mountEvolutionCharts`.
 */
function buildEvolutionCard(
  distance: TargetDistanceKey,
  series: readonly EvolutionPoint[]
): { card: HTMLElement; canvas: HTMLCanvasElement | null } {
  const card = document.createElement('div');
  card.className = 'pr-evolution-card card';

  const heading = document.createElement('h3');
  heading.className = 'text-heading';
  heading.textContent = DISTANCE_LABELS[distance];
  card.appendChild(heading);

  const summary = evolutionCardSummary(series);

  const valueEl = document.createElement('div');
  valueEl.className = 'text-display';
  valueEl.textContent = summary.currentSec !== null ? formatEffortDuration(summary.currentSec) : '—';
  card.appendChild(valueEl);

  const labelEl = document.createElement('div');
  labelEl.className = 'text-label';
  labelEl.textContent =
    summary.steps > 0 ? `${summary.steps} steps, ${summary.firstYear}–${summary.lastYear}` : 'No PR history yet';
  card.appendChild(labelEl);

  if (series.length === 0) {
    return { card, canvas: null };
  }

  const canvasWrap = document.createElement('div');
  canvasWrap.className = 'pr-evolution-card__canvas-wrap';
  const canvas = document.createElement('canvas');
  canvasWrap.appendChild(canvas);
  card.appendChild(canvasWrap);

  const details = document.createElement('details');
  details.className = 'pr-evolution-card__details';
  const summaryEl = document.createElement('summary');
  summaryEl.textContent = `Show progression (${series.length} steps)`;
  details.appendChild(summaryEl);
  details.appendChild(buildProgressionTable(series));
  card.appendChild(details);

  return { card, canvas };
}

function buildEvolutionSection(activities: BestEffortsDocument['activities']): {
  section: HTMLElement;
  heading: HTMLElement;
  chartCards: EvolutionChartCard[];
} {
  const section = document.createElement('section');
  section.id = 'records-pr-evolution';

  const heading = document.createElement('h2');
  heading.className = 'text-heading';
  heading.tabIndex = -1;
  heading.textContent = 'PR Evolution';
  section.appendChild(heading);

  const grid = document.createElement('div');
  grid.className = 'pr-evolution-grid';

  const chartCards: EvolutionChartCard[] = [];

  for (const distance of TARGET_ORDER) {
    const series = buildEvolutionSeries(activities, distance);
    const { card, canvas } = buildEvolutionCard(distance, series);
    grid.appendChild(card);
    if (canvas) {
      chartCards.push({ distance, displayName: DISTANCE_LABELS[distance], canvas, points: series });
    }
  }

  section.appendChild(grid);
  return { section, heading, chartCards };
}

