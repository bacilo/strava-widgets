export interface RecordsViewDeps {
  indexClient: IndexClient;
  fetchImpl?: FetchLike;
}

export function createRecordsView(deps: RecordsViewDeps): DashboardView {
  let mountedContainer: HTMLElement | null = null;
  let resizeListener: (() => void) | null = null;
  let sectionObserver: IntersectionObserver | null = null;
  let chartsHandle: EvolutionChartsHandle | null = null;

  function cleanupInteractive(): void {
    if (resizeListener) {
      window.removeEventListener('resize', resizeListener);
      resizeListener = null;
    }
    if (sectionObserver) {
      sectionObserver.disconnect();
      sectionObserver = null;
    }
    if (chartsHandle) {
      chartsHandle.destroy();
      chartsHandle = null;
    }
  }

  async function load(ctx: ViewMountContext): Promise<void> {
    cleanupInteractive();
    ctx.container.replaceChildren();

    const loading = document.createElement('div');
    loading.className = 'loading-indicator';
    loading.setAttribute('role', 'status');
    loading.textContent = 'Loading records…';
    ctx.container.appendChild(loading);

    const doFetch = deps.fetchImpl ?? (globalThis.fetch as unknown as FetchLike);

    const [bestEfforts, ageGrading, weekly, monthly, streaks, exclusionsRaw] = await Promise.all([
      fetchStatsJson<BestEffortsDocument>(`${STATS_BASE_URL}best-efforts.json`, doFetch),
      fetchStatsJson<AgeGradingDocument>(`${STATS_BASE_URL}age-grading.json`, doFetch),
      fetchStatsJson<unknown>(`${STATS_BASE_URL}weekly-distance.json`, doFetch),
      fetchStatsJson<unknown>(`${STATS_BASE_URL}monthly-stats.json`, doFetch),
      fetchStatsJson<unknown>(`${STATS_BASE_URL}streaks.json`, doFetch),
      fetchStatsJson<unknown>(EXCLUSIONS_URL, doFetch),
    ]);

    // mount() may resolve after the view was unmounted (fast navigation away
    // before the fetch finished) — never paint into a container this view no
    // longer owns.
    if (mountedContainer !== ctx.container) return;

    if (bestEfforts === null) {
      renderErrorState(ctx.container, () => {
        void load(ctx);
      });
      return;
    }

    ctx.container.replaceChildren();

    const view = document.createElement('div');
    view.className = 'view';

    const h1 = document.createElement('h1');
    h1.className = 'text-heading';
    h1.textContent = 'Records';
    h1.tabIndex = -1;
    view.appendChild(h1);

    const exclusionReasons = buildExclusionReasonIndex(exclusionsRaw);
    const superlatives = selectSuperlatives(weekly, monthly, streaks);

    const superlativesSection = buildSuperlativesSection(superlatives);
    const prTablesSection = buildPrTablesSection(bestEfforts, ageGrading, exclusionReasons);
    const evolution = buildEvolutionSection(bestEfforts.activities);
    const predictions = buildPredictionsSection(bestEfforts);

    const superlativesHeading = superlativesSection.querySelector('h2')!;
    const prTablesHeading = prTablesSection.querySelector('h2')!;

    const jumpTargets: JumpTarget[] = [
      { section: superlativesSection, heading: superlativesHeading, label: 'Superlatives' },
      { section: prTablesSection, heading: prTablesHeading, label: 'PR Tables' },
      { section: evolution.section, heading: evolution.heading, label: 'PR Evolution' },
      { section: predictions.section, heading: predictions.heading, label: 'Race Predictions' },
    ];

    const { nav, buttons } = buildJumpList(jumpTargets);

    view.appendChild(nav);
    view.appendChild(superlativesSection);
    view.appendChild(prTablesSection);
    view.appendChild(evolution.section);
    view.appendChild(predictions.section);

    ctx.container.appendChild(view);

    // Every hash navigation announces a context change to assistive tech
    // (17-UI-SPEC § 5 Cross-Surface focus management), same discipline as
    // every other Phase 16/17 view.
    h1.focus();

    updateJumpOffset(nav);
    const onResize = () => updateJumpOffset(nav);
    window.addEventListener('resize', onResize);
    resizeListener = onResize;

    sectionObserver = wireActiveSectionObserver(
      jumpTargets.map((target, i) => ({ section: target.section, button: buttons[i] }))
    );

    if (evolution.chartCards.length > 0) {
      const chartsModule = await import('./records-charts.js');
      if (mountedContainer !== ctx.container) return;
      chartsHandle = chartsModule.mountEvolutionCharts(evolution.chartCards);
    }
  }

  return {
    route: ROUTES.RECORDS,
    title: 'Records',
    navEntry: RECORDS_NAV_ENTRY,

    async mount(ctx: ViewMountContext): Promise<void> {
      mountedContainer = ctx.container;
      await load(ctx);
    },

    unmount(): void {
      cleanupInteractive();
      mountedContainer?.replaceChildren();
      mountedContainer = null;
    },
  };
}
