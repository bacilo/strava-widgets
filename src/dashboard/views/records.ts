/**
 * Builds one tile: value (`.text-display`) + category label + an optional
 * context sub-label — two `.text-label` lines rather than one, reusing the
 * existing role twice (zero new CSS) so the tile still names its own
 * category even though `overview.ts`'s `buildStatCard` anatomy only ever
 * needed a single label line.
 */
function buildSuperlativeTile(value: string, label: string, sublabel?: string): HTMLElement {
  const wrapper = document.createElement('div');

  const valueEl = document.createElement('div');
  valueEl.className = 'text-display';
  valueEl.textContent = value;
  wrapper.appendChild(valueEl);

  const labelEl = document.createElement('div');
  labelEl.className = 'text-label';
  labelEl.textContent = label;
  wrapper.appendChild(labelEl);

  if (sublabel) {
    const subEl = document.createElement('div');
    subEl.className = 'text-label';
    subEl.textContent = sublabel;
    wrapper.appendChild(subEl);
  }

  return wrapper;
}

function buildSuperlativesSection(superlatives: Superlatives): HTMLElement {
  const section = document.createElement('section');
  section.id = 'records-superlatives';

  const heading = document.createElement('h2');
  heading.className = 'text-heading';
  heading.tabIndex = -1;
  heading.textContent = 'Superlatives';
  section.appendChild(heading);

  const card = document.createElement('div');
  card.className = 'card detail-section';

  const grid = document.createElement('div');
  grid.className = 'stat-grid';

  const { biggestWeek, biggestMonth, longestStreak, currentStreak } = superlatives;

  grid.appendChild(
    buildSuperlativeTile(
      biggestWeek ? `${biggestWeek.km.toFixed(1)} km` : '—',
      'Biggest Week',
      biggestWeek ? `week of ${formatActivityDate(biggestWeek.weekStartISO)}` : undefined
    )
  );
  grid.appendChild(
    buildSuperlativeTile(
      biggestMonth ? `${biggestMonth.km.toFixed(1)} km` : '—',
      'Biggest Month',
      biggestMonth ? biggestMonth.label : undefined
    )
  );
  grid.appendChild(
    buildSuperlativeTile(
      longestStreak ? `${longestStreak.days} days` : '—',
      'Longest Streak',
      longestStreak
        ? `${formatActivityDate(longestStreak.startISO)} – ${formatActivityDate(longestStreak.endISO)}`
        : undefined
    )
  );
  // A `0`-day current streak is a real value (T-18-HONEST-05) — the tile
  // only falls back to an em-dash when the whole `currentStreak` OBJECT is
  // absent, never because `days` happens to be zero.
  grid.appendChild(
    buildSuperlativeTile(
      currentStreak ? `${currentStreak.days} days` : '—',
      'Current Streak',
      currentStreak
        ? currentStreak.active
          ? 'active'
          : currentStreak.endedISO
            ? `ended ${formatActivityDate(currentStreak.endedISO)}`
            : undefined
        : undefined
    )
  );

  card.appendChild(grid);
  section.appendChild(card);
  return section;
}

