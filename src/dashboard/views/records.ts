/**
 * Fetches and parses a small stats JSON file, using the same non-ok error
 * shape as the data clients. Individually degrade-guarded so a missing
 * stats file (gitignored, regenerated by a compute run) never fails the
 * whole view — it degrades to `null`, which each section renders as its own
 * named absence rather than throwing (mirrors `overview.ts`'s idiom).
 */
async function fetchStatsJson<T>(url: string, doFetch: FetchLike): Promise<T | null> {
  try {
    const response = await doFetch(url);
    if (!response.ok) {
      throw new Error(`Failed to fetch data: ${response.status} ${response.statusText}`);
    }
    return (await response.json()) as T;
  } catch (error) {
    console.error(error);
    return null;
  }
}

